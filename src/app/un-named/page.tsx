"use client";

import { cn } from "@/lib/utils";
import { AnimatePresence, motion, scale } from "motion/react";
import { useMemo, useState } from "react";

const items = ["Ideate", "Build", "Refine", "Launch"];

export default function SmoothStepper() {
  const [currentStep, setCurrentStep] = useState(0);

  const content = useMemo(() => {
    switch (currentStep) {
      case 0:
        return "Ideate";
      case 1:
        return "Build";
      case 2:
        return "Refine";
      case 3:
        return "Launch";
    }
  }, [currentStep]);

  return (
    <div className="w-full h-full flex flex-col gap-4 items-center justify-center">
      <motion.div className="flex font-medium text-lg">
        <AnimatePresence mode="popLayout">
          {content?.split("").map((char, idx) => (
            <motion.div
              className=""
              initial={{ y: 11, opacity: 0, scale: 0.4, filter: "blur(4px)" }}
              animate={{ y: 0, opacity: 1, scale: 1, filter: "blur(0px)" }}
              exit={{ y: -11, opacity: 0, scale: 0.3, filter: "blur(4px)" }}
              transition={{ delay: 0.037 * idx }}
              key={`${idx}-${char}`}
            >
              {char}
            </motion.div>
          ))}
        </AnimatePresence>
      </motion.div>

      <div className="flex gap-3">
        <motion.button
          whileTap={{ scale: 0.97 }}
          className="p-4 rounded-full bg-zinc-900 hover:bg-zinc-900/80 group"
          onClick={() => {
            if (currentStep === 0) {
              return;
            }
            setCurrentStep((prev) => prev - 1);
          }}
        >
          <span className="group-hover:opacity-75">
            <svg
              className="w-4 h-4"
              width="16"
              height="18"
              viewBox="0 0 16 18"
              fill="none"
              xmlns="http://www.w3.org/2000/svg"
            >
              <path
                d="M1 7.26795C-0.333333 8.03775 -0.333332 9.96225 1 10.7321L13 17.6603C14.3333 18.4301 16 17.4678 16 15.9282L16 2.0718C16 0.532196 14.3333 -0.430055 13 0.339746L1 7.26795Z"
                fill="#D9D9D9"
              />
            </svg>
          </span>
        </motion.button>

        <motion.div className="px-6 py-2 rounded-full border-zinc-800 bg-zinc-800/70">
          <div className="flex items-center gap-4">
            {items.map((label) => (
              <div
                key={label}
                className="relative size-7 flex items-center justify-center"
              >
                <AnimatePresence initial={false} mode="popLayout">
                  {label === content ? (
                    <motion.div
                      key="icon"
                      initial={{
                        scale: 0,
                        opacity: 0,
                        rotate: -20,
                        filter: "blur(4px)",
                      }}
                      animate={{
                        scale: 1,
                        opacity: 1,
                        rotate: 0,
                        filter: "blur(0px)",
                      }}
                      exit={{
                        scale: 0.4,
                        opacity: 0,
                        rotate: 20,
                        filter: "blur(4px)",
                      }}
                      transition={{
                        type: "spring",
                        stiffness: 300,
                        damping: 24,
                      }}
                      className="text-white"
                    >
                      {label === "Ideate" ? (
                        <IdeateIcon />
                      ) : label === "Build" ? (
                        <CreateIcon />
                      ) : label === "Refine" ? (
                        <RefineIcon />
                      ) : (
                        <LaunchIcon />
                      )}
                    </motion.div>
                  ) : (
                    <motion.span
                      key="dot"
                      className="block size-2 rounded-full bg-zinc-600/80"
                      initial={{ scale: 0.7, opacity: 0.6 }}
                      animate={{ scale: 1, opacity: 1 }}
                      exit={{ scale: 0.7, opacity: 0 }}
                      transition={{ duration: 0.18 }}
                    />
                  )}
                </AnimatePresence>
              </div>
            ))}
          </div>
        </motion.div>

        <motion.button
          whileTap={{ scale: 0.97 }}
          className="p-4 rounded-full bg-zinc-900 hover:bg-zinc-900/80 group"
          onClick={() => {
            if (currentStep === 3) {
              return;
            }
            setCurrentStep((prev) => prev + 1);
          }}
        >
          <span className="group-hover:opacity-75">
            <svg
              className="w-4 h-4"
              width="16"
              height="18"
              viewBox="0 0 16 18"
              fill="none"
              xmlns="http://www.w3.org/2000/svg"
            >
              <path
                d="M15 7.26795C16.3333 8.03775 16.3333 9.96225 15 10.7321L3 17.6603C1.66667 18.4301 -8.94676e-07 17.4678 -8.27378e-07 15.9282L-2.21695e-07 2.0718C-1.54397e-07 0.532196 1.66667 -0.430055 3 0.339746L15 7.26795Z"
                fill="#D9D9D9"
              />
            </svg>
          </span>
        </motion.button>
      </div>
    </div>
  );
}

